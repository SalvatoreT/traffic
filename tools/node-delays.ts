// Measured control delay by control type, from kept simulator seed reports with per-link delays (calibrate --seeds ... --keep-seeds DIR), and the one file both routers read.
//   npx tsx tools/node-delays.ts --dir DIR [--period pm_peak] [--seeds 1-10] [--area rockridge] [--write]
// Delay of a link = mean time lost against the speed limit per vehicle, including the stop at its end. The router adds a control delay per movement on top of the movement's own
// traversal time and turn penalty, so the constant is the delay of the links that end at the control minus the delay of links that end at no control (car following, turn slowdown,
// crossing conflicts), flow-weighted over the seeds and the links with at least 20 veh/h. --write rewrites crates/sim/data/node-delays.json (values rounded to 0.5 s) and the report.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { readSeeds } from './lib/assess';
import { buildGraph } from './lib/assign';

const root = resolve(import.meta.dirname, '..');
const arg = (k: string, d: string) => { const i = process.argv.indexOf(k); return i >= 0 ? process.argv[i + 1] : d; };
const area = arg('--area', 'rockridge'), period = arg('--period', 'pm_peak'), dir = resolve(root, arg('--dir', ''));
const [s0, s1] = arg('--seeds', '1-10').split('-').map(Number);
const runs = readSeeds(dir, area, period, Array.from({ length: s1 - s0 + 1 }, (_, i) => s0 + i));
if (!runs.length || !runs[0].linkMeanDelayS) { console.error('node-delays: no seed reports with link delays in --dir'); process.exit(1); }
const net = JSON.parse(readFileSync(resolve(root, `public/data/${area}.network.json`), 'utf8'));
const g = buildGraph(net.nodes, net.links, net.turnBans ?? [], period);
const nodeBy = new Map<number, { control: string }>(net.nodes.map((n: { id: number; control: string }) => [n.id, n]));
const nL = net.links.length;
const flow = new Float64Array(nL), dsum = new Float64Array(nL);
for (const r of runs) for (let l = 0; l < nL; l++) { flow[l] += r.linkFlowVehPerHour![l]; dsum[l] += r.linkFlowVehPerHour![l] * r.linkMeanDelayS![l]; }
const groups = new Map<string, { n: number; w: number; d: number; dd: number[]; ww: number[] }>();
for (let l = 0; l < nL; l++) {
  if (flow[l] / runs.length < 20 || net.links[l].class === 'motorway') continue;
  const c = nodeBy.get(net.links[l].to)!.control;
  const hump = net.links[l].humps?.length ? 'hump' : 'no hump';
  const key = c === 'two_way_stop' ? (g.minor[l] ? 'minor stop' : 'major street at a two-way stop') : c === 'all_way_stop' ? 'all-way stop' : c === 'signal' ? 'signal' : c === 'traffic_circle' ? 'circle' : `uncontrolled, ${hump}`;
  const e = groups.get(key) ?? groups.set(key, { n: 0, w: 0, d: 0, dd: [], ww: [] }).get(key)!;
  const d = dsum[l] / flow[l];
  e.n++; e.w += flow[l]; e.d += dsum[l]; e.dd.push(d); e.ww.push(flow[l]);
}
const wmedian = (k: string) => {
  const e = groups.get(k);
  if (!e) return NaN;
  const idx = e.dd.map((_, i) => i).sort((a, b) => e.dd[a] - e.dd[b]);
  let acc = 0;
  for (const i of idx) { acc += e.ww[i]; if (acc >= e.w / 2) return e.dd[i]; }
  return NaN;
};
// Median, flow-weighted: a few jammed approaches carry a queueing delay that the route-cost updates already hold; the constant is the delay a typical vehicle meets at the control.
const mean = wmedian;
const base = mean('uncontrolled, no hump');
const round = (x: number) => Math.round(x * 2) / 2;
const out = { signal: round(Math.max(0, mean('signal') - base)), allWayStop: round(Math.max(0, mean('all-way stop') - base)), minorStop: round(Math.max(0, mean('minor stop') - base)), circle: round(Math.max(0, (Number.isFinite(mean('circle')) ? mean('circle') : base + 3) - base)) };
const cur = JSON.parse(readFileSync(resolve(root, 'crates/sim/data/node-delays.json'), 'utf8'));
const L = [`# Control delay by control type: ${area}, ${period}`, '', `Generated by \`tools/node-delays.ts\` (do not edit). Kept seed reports ${s0} to ${s1} (${runs.length} runs), links with at least 20 veh/h on average, motorway links left out. Simulated delay = time lost against the speed limit per vehicle on the link, stop at its end included, flow-weighted. Router constant = flow-weighted median link delay of the group (a few jammed approaches would otherwise set the constant; their queueing is in the route costs the simulator updates every epoch) minus that of links that end at no control (${base.toFixed(1)} s: car following and turn slowdown, which the router adds through the movement's own traversal time and turn penalty).`, '', '| Link group | Links | Flow-weighted mean delay (s) | Flow-weighted median (s) | Router constant now (s) | Router constant from this run (s) |', '| --- | --- | --- | --- | --- | --- |'];
const now: Record<string, number | string> = { signal: cur.signal, 'all-way stop': cur.allWayStop, 'minor stop': cur.minorStop, circle: cur.circle };
const next: Record<string, number> = { signal: out.signal, 'all-way stop': out.allWayStop, 'minor stop': out.minorStop, circle: out.circle };
for (const [k, e] of [...groups].sort((a, b) => b[1].w - a[1].w)) { const s = [...e.dd].sort((a, b) => a - b); L.push(`| ${k} | ${e.n} | ${(e.d / e.w).toFixed(1)} | ${wmedian(k).toFixed(1)} | ${now[k] ?? '-'} | ${next[k] ?? '-'} |`); }
console.log(L.join('\n'));
console.log(JSON.stringify(out));
if (process.argv.includes('--write')) {
  writeFileSync(resolve(root, 'crates/sim/data/node-delays.json'), JSON.stringify({ note: cur.note, ...out }, null, 2) + '\n');
  writeFileSync(resolve(root, `data/calibration/${area}.node-delays.md`), L.join('\n') + '\n');
}
