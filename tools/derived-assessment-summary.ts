// Condenses one or more assessments (change derived-targets-not-judged) into the figures the project lead reviews: the verdict rows (D16, D5, the station rule on the new scope, whole-street
// traversals), the pass counts under both scopes, the derived-target tables and the held-out misses. It only reads the Markdown that tools/assess.ts wrote.
//   npx tsx tools/derived-assessment-summary.ts LABEL=FILE [LABEL=FILE ...]
import { readFileSync } from 'node:fs';
import { DERIVED_TARGET_PHRASE } from './lib/derived-targets';

const inputs = process.argv.slice(2).map((a) => { const i = a.indexOf('='); if (i < 0) { console.error('usage: derived-assessment-summary.ts LABEL=FILE ...'); process.exit(2); } return { label: a.slice(0, i), file: a.slice(i + 1) }; });
if (!inputs.length) { console.error('usage: derived-assessment-summary.ts LABEL=FILE ...'); process.exit(2); }

/** The lines of the table that starts at the first line beginning with `header`, at or after `from`. */
function table(lines: string[], header: string, from = 0): string[] {
  const at = lines.findIndex((l, i) => i >= from && l.startsWith(header));
  if (at < 0) return [];
  const out: string[] = [];
  for (let i = at; i < lines.length && lines[i].startsWith('|'); i++) out.push(lines[i]);
  return out;
}

const L: string[] = ['# Derived targets: assessment summary', ''];
for (const { label, file } of inputs) {
  const text = readFileSync(file, 'utf8');
  const lines = text.split('\n');
  const verdictAt = lines.findIndex((l) => l === '## Verdict');
  const stamp = lines.find((l) => l.startsWith('Generated by'))?.replace(/ Rules: .*$/, '') ?? '';
  L.push(`## ${label}`, '', `Source: \`${file}\`.`, '', stamp.slice(0, 700), '');
  const status = lines.find((l) => l.startsWith('Suggested status') || l.startsWith('**No status is suggested'));
  L.push('### Verdict rows', '', ...table(lines, '| Period | D16 |', verdictAt), '');
  const scopeAt = lines.findIndex((l, i) => i > verdictAt && l.startsWith('Scope of the station rule'));
  if (scopeAt >= 0) L.push('### Station rule under both scopes', '', lines[scopeAt], '', ...table(lines, '| Period | New scope', scopeAt), '');
  L.push('### Whole-street traversals', '', ...table(lines, '| Period | Street and direction', verdictAt), '');
  const miss = lines.findIndex((l, i) => i > verdictAt && l.startsWith('Recent held-out stations at GEH 5 or more'));
  L.push('### Held-out misses on the cross-validation demand (hourly counts only)', '', ...(miss >= 0 ? table(lines, '| Period | Station |', miss) : ['None.']), '');
  for (const p of ['am_peak', 'midday', 'pm_peak']) {
    const sec = lines.findIndex((l) => l === `## ${p}`);
    if (sec < 0) continue;
    const next = lines.findIndex((l, i) => i > sec && l.startsWith('## '));
    const stop = next < 0 ? lines.length : next;
    const at = lines.findIndex((l, i) => i > sec && i < stop && l.startsWith(`Targets ${DERIVED_TARGET_PHRASE}.`));
    if (at < 0) { L.push(`### Derived targets, ${p}`, '', 'No link-based derived target has a target in this period, or no station file was scored.', ''); continue; }
    const end = lines.findIndex((l, i) => i > at && i < stop && /^\d+ link-based derived targets in /.test(l));
    L.push(`### Derived targets, ${p}`, '', ...table(lines, '| Station | Source and count year', at), '', end >= 0 ? lines[end] : '', '');
  }
  L.push('### Status', '', status ?? 'No status line.', '');
}
console.log(L.join('\n'));
