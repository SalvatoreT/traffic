//! Validation suite: runs the benchmark cases of `traffic_sim::validate` and writes `data/calibration/validation.md`.
//!
//! cargo run --release -p traffic-sim --bin validate [-- --out PATH] [--before before.json] [--json] [--no-write]

use std::fmt::Write as _;
use std::path::PathBuf;
use traffic_sim::validate::{run_all, Case};

fn fmt(v: f64) -> String {
    if v.abs() >= 100.0 {
        format!("{v:.0}")
    } else if v.abs() >= 10.0 {
        format!("{v:.1}")
    } else {
        format!("{v:.2}")
    }
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let get = |k: &str| args.iter().position(|a| a == k).and_then(|i| args.get(i + 1)).cloned();
    let out = get("--out").map(PathBuf::from).unwrap_or_else(|| PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../data/calibration/validation.md"));
    let cases: Vec<Case> = run_all();
    if args.iter().any(|a| a == "--json") {
        println!("{}", serde_json::to_string(&cases).unwrap());
        return;
    }
    let before: Vec<Case> = get("--before").and_then(|p| std::fs::read_to_string(p).ok()).and_then(|t| serde_json::from_str(&t).ok()).unwrap_or_default();
    let mut md = String::new();
    let _ = writeln!(md, "# Validation suite\n");
    let _ = writeln!(md, "Generated by `cargo run --release -p traffic-sim --bin validate`. Each case is a tiny synthetic network with saturated demand (cars only unless the case says otherwise) that measures one primitive against a published range. Seed 1; cases a to e, g, h and i run 1,500 to 2,700 s of simulated time. The ratio is the simulated value over the midpoint of the expected range. Before is the same case on the simulator at the start of the fifth calibration round. A source of ASSUMPTION marks a range with no verified source (see `docs/references.md` for the keys).\n");
    let _ = writeln!(md, "| Case | Quantity | Unit | Before | Sim | Expected | Ratio | Source | Result | Note |\n| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |");
    let line = |c: &Case| {
        let b = before.iter().find(|b| b.id == c.id);
        let bs = b.map(|b| format!("{} ({})", fmt(b.sim), if b.pass() { "ok" } else { "fail" })).unwrap_or_else(|| "-".into());
        format!("| {} | {} | {} | {} | {} | {} to {} | {:.2} | {} | {} | {} |", c.id, c.name, c.unit, bs, fmt(c.sim), fmt(c.lo), fmt(c.hi), c.ratio(), c.source, if c.pass() { "pass" } else { "FAIL" }, c.note)
    };
    for c in &cases {
        let l = line(c);
        println!("{:4} {:78} {:>8} [{} .. {}] {:>5.2} {}", c.id, c.name, fmt(c.sim), fmt(c.lo), fmt(c.hi), c.ratio(), if c.pass() { "ok" } else { "FAIL" });
        let _ = writeln!(md, "{l}");
    }
    let n_fail = cases.iter().filter(|c| !c.pass()).count();
    let _ = writeln!(md, "\n{} of {} cases pass.", cases.len() - n_fail, cases.len());
    println!("{} of {} cases pass", cases.len() - n_fail, cases.len());
    if !args.iter().any(|a| a == "--no-write") {
        if let Some(d) = out.parent() {
            let _ = std::fs::create_dir_all(d);
        }
        std::fs::write(&out, md).expect("write validation.md");
        println!("wrote {}", out.display());
    }
}
